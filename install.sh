#!/usr/bin/env bash
# Nova LiveOS installer — v1.0.0
# Idempotent and fail-closed: any failed step stops the install with a
# message saying exactly what to fix. It provisions a FRESH Supabase project
# (created by you — see docs/INSTALL.md step 1, account/project creation is a
# dashboard step no script can do for you) and deploys the static shell to
# Cloudflare Pages. No server is created, ever.
set -euo pipefail
cd "$(dirname "$0")"

say()  { printf '\n== %s\n' "$*"; }
die()  { printf '\nINSTALL STOPPED: %s\n' "$*" >&2; exit 1; }

# ------------------------------------------------------------ 0. env + tools
say "Step 0 — environment"
[ -f .env ] || die "no .env file. Copy .env.example to .env and fill in your NEW Supabase project's URL + anon key first."
set -a; # shellcheck disable=SC1091
source .env; set +a
[ -n "${SUPABASE_URL:-}" ] || die "SUPABASE_URL is empty in .env"
[ -n "${SUPABASE_ANON_KEY:-}" ] || die "SUPABASE_ANON_KEY is empty in .env"
case "$SUPABASE_URL" in
  https://*.supabase.co) ;;
  *) die "SUPABASE_URL must look like https://<project-ref>.supabase.co — got: $SUPABASE_URL" ;;
esac
case "$SUPABASE_ANON_KEY" in *YOUR*|*PLACEHOLDER*) die "SUPABASE_ANON_KEY still holds a placeholder value" ;; esac
command -v curl >/dev/null || die "curl is required"
echo "Supabase project: $SUPABASE_URL"

# ------------------------------------------------- 1. database (migrations)
say "Step 1 — database schema + seed"
if command -v supabase >/dev/null 2>&1 && [ -n "${SUPABASE_PROJECT_REF:-}" ]; then
  echo "Using the Supabase CLI path (supabase link + db push)."
  supabase link --project-ref "$SUPABASE_PROJECT_REF"
  supabase db push
  if command -v psql >/dev/null 2>&1 && [ -n "${SUPABASE_DB_URL:-}" ]; then
    psql "$SUPABASE_DB_URL" -f supabase/seed.sql
  else
    echo "NOTE: seed not auto-applied (no SUPABASE_DB_URL/psql). Paste supabase/seed.sql into the SQL editor once (docs/INSTALL.md step 2b)."
  fi
else
  cat <<'EOF'
The Supabase CLI path is unavailable (CLI missing or SUPABASE_PROJECT_REF unset).
Use the manual path — it is exact and takes two minutes:
  1. Open your project at https://supabase.com/dashboard → SQL Editor.
  2. Paste the full contents of supabase/migrations/0001_kernel.sql → Run.
  3. Paste the full contents of supabase/seed.sql → Run.
Both files are idempotent, so re-running them is safe.
EOF
  read -r -p "Press Enter once both files have run successfully (Ctrl-C to stop): " _
fi

# ------------------------------------------------------------ 2. shell config
say "Step 2 — write public/config.js"
cat > public/config.js <<EOF
// Nova LiveOS configuration — generated by install.sh (v1.0.0)
// Anon (public) key only. Never put a service-role key in this file.
window.LIVEOS_CONFIG = {
  version: "1.0.0",
  supabaseUrl: "$SUPABASE_URL",
  supabaseAnonKey: "$SUPABASE_ANON_KEY"
};
EOF
echo "public/config.js written for $SUPABASE_URL"

# ------------------------------------------------------------- 3. health check
say "Step 3 — verify the database answers"
code=$(curl -s -o /tmp/liveos-modules.json -w '%{http_code}' \
  "$SUPABASE_URL/rest/v1/modules?select=slug,name,published&published=eq.true" \
  -H "apikey: $SUPABASE_ANON_KEY" -H "Authorization: Bearer $SUPABASE_ANON_KEY")
[ "$code" = "200" ] || die "modules endpoint returned HTTP $code (expected 200). Did the migration + seed run? Is the anon key correct?"
grep -q 'team-board' /tmp/liveos-modules.json || die "modules endpoint answered but team-board is missing — run supabase/seed.sql."
echo "Modules endpoint OK: $(cat /tmp/liveos-modules.json)"

# ------------------------------------------------------ 4. deploy the shell
say "Step 4 — deploy the shell to Cloudflare Pages"
if command -v wrangler >/dev/null 2>&1; then
  wrangler pages deploy public --project-name "${CLOUDFLARE_PAGES_PROJECT:-nova-liveos}"
else
  echo "wrangler not found — deploy manually once:"
  echo "  npx wrangler pages deploy public --project-name ${CLOUDFLARE_PAGES_PROJECT:-nova-liveos}"
  echo "or drag the public/ folder into Cloudflare dashboard → Pages → Create → Upload assets."
fi

say "Step 5 — final verification"
echo "Open your Pages URL, install the app, and open the Module Store:"
echo "the three proof modules (Team Board, Mini Shop, Agent Floor) should be listed."
echo "Then edit any row in the Supabase Table Editor — the shell updates live."
echo "Done. Nova LiveOS v1.0.0 is installed — with no server to keep alive."
